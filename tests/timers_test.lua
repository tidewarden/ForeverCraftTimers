local T = ...

local function fresh()
    local FCT = { db = {} }
    assert(loadfile(T.root .. "/Timers.lua"))("ForeverCraftTimers", FCT)
    return FCT, FCT.Timers
end

T.test("timers_record_then_alert_once_when_due", function()
    local FCT, Tm = fresh()
    Tm.Record(FCT.db, "Alc-Realm", "transmute", 1000, "Arcanite", 500)
    T.eq(#Tm.TakeDue(FCT.db, 999), 0)
    local due = Tm.TakeDue(FCT.db, 1000)
    T.eq(#due, 1); T.eq(due[1].char, "Alc-Realm"); T.eq(due[1].label, "Arcanite")
    T.eq(#Tm.TakeDue(FCT.db, 5000), 0, "announced only once")
end)

T.test("timers_expired_while_offline_is_announced_later", function()
    local FCT, Tm = fresh()
    Tm.Record(FCT.db, "Tailor-Realm", "mooncloth", 1000, nil, 0)
    T.eq(#Tm.TakeDue(FCT.db, 999999), 1)
end)

T.test("timers_new_cooldown_rearms_alert", function()
    local FCT, Tm = fresh()
    Tm.Record(FCT.db, "A-R", "mooncloth", 100, nil, 0)
    Tm.TakeDue(FCT.db, 200)
    Tm.Record(FCT.db, "A-R", "mooncloth", 900, nil, 200)
    T.eq(#Tm.TakeDue(FCT.db, 900), 1)
end)

T.test("timers_set_ready_by_hand_does_not_alert", function()
    local FCT, Tm = fresh()
    Tm.Record(FCT.db, "A-R", "saltshaker", 50, nil, 50)
    T.eq(#Tm.TakeDue(FCT.db, 60), 0)
end)

T.test("timers_mark_known_never_shortens_a_running_timer", function()
    local FCT, Tm = fresh()
    Tm.Record(FCT.db, "A-R", "transmute", 5000, "Arcanite", 0)
    Tm.MarkKnown(FCT.db, "A-R", "transmute")
    T.eq(FCT.db.chars["A-R"].cds.transmute.expires, 5000)
    Tm.MarkKnown(FCT.db, "A-R", "mooncloth")
    T.eq(FCT.db.chars["A-R"].cds.mooncloth.expires, 0)
    T.eq(#Tm.TakeDue(FCT.db, 10), 0, "known-and-ready doesn't alert")
end)

T.test("timers_rows_current_char_first_and_remaining", function()
    local FCT, Tm = fresh()
    Tm.Record(FCT.db, "Bob-R", "mooncloth", 400, nil, 0)
    Tm.Record(FCT.db, "Zed-R", "transmute", 100, nil, 0)
    Tm.Record(FCT.db, "Zed-R", "saltshaker", 300, nil, 0)
    local rows = Tm.Rows(FCT.db, 200, "Zed-R")
    T.eq(rows[1].char, "Zed-R"); T.eq(rows[2].char, "Bob-R")
    T.eq(rows[1].cds[1].key, "transmute"); T.eq(rows[1].cds[1].remaining, 0)
    T.eq(rows[1].cds[2].key, "saltshaker"); T.eq(rows[1].cds[2].remaining, 100)
end)

T.test("timers_format", function()
    local _, Tm = fresh()
    T.eq(Tm.Format(0), "Ready")
    T.eq(Tm.Format(30), "<1m")
    T.eq(Tm.Format(125 * 60), "2h 5m")
    T.eq(Tm.Format(2 * 86400 + 3 * 3600 + 59), "2d 3h")
end)

T.test("timers_parse_duration", function()
    local _, Tm = fresh()
    T.eq(Tm.ParseDuration("2d5h"), 2 * 86400 + 5 * 3600)
    T.eq(Tm.ParseDuration("3h 20m"), 3 * 3600 + 20 * 60)
    T.eq(Tm.ParseDuration("45"), 45 * 60)
    T.eq(Tm.ParseDuration("soon"), nil)
    T.eq(Tm.ParseDuration(""), nil)
end)

T.test("timers_resolve_and_label", function()
    local _, Tm = fresh()
    T.eq(Tm.Resolve("Salt"), "saltshaker"); T.eq(Tm.Resolve("arcanite"), "transmute"); T.eq(Tm.Resolve("x"), nil)
    T.eq(Tm.LabelFromSpellName("Transmute: Arcanite"), "Arcanite")
end)

T.test("timers_forget_by_name", function()
    local FCT, Tm = fresh()
    Tm.Record(FCT.db, "Alc-Realm", "transmute", 1, nil, 0)
    T.eq(Tm.Forget(FCT.db, "alc"), true)
    T.eq(FCT.db.chars["Alc-Realm"], nil)
end)

T.test("timers_small_wobble_after_alert_does_not_alert_again", function()
    local FCT, Tm = fresh()
    Tm.Record(FCT.db, "A-R", "transmute", 1000, nil, 0)
    T.eq(#Tm.TakeDue(FCT.db, 1000), 1)
    Tm.Record(FCT.db, "A-R", "transmute", 1001, nil, 1000) -- a rescan reads one second more
    T.eq(#Tm.TakeDue(FCT.db, 1002), 0)
end)

T.test("timers_guess_flag_cleared_by_real_reading", function()
    local FCT, Tm = fresh()
    Tm.Record(FCT.db, "A-R", "transmute", 172800, "Arcanite", 0, "guess")
    T.eq(Tm.Rows(FCT.db, 0, "A-R")[1].cds[1].guess, true)
    Tm.Record(FCT.db, "A-R", "transmute", 82800, nil, 0)
    local cd = Tm.Rows(FCT.db, 0, "A-R")[1].cds[1]
    T.eq(cd.guess, nil); T.eq(cd.remaining, 82800); T.eq(cd.label, "Arcanite")
end)
